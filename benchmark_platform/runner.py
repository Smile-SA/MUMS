# Scenario sections, one module each. `post-processing` is optional.
REQUIRED_COMPONENTS = ("environment", "observability", "stack", "traffic", "optimizer")
OPTIONAL_COMPONENTS = ("post-processing",)

# External commands the core itself needs (Kubernetes state collection), checked
# before anything runs: pip cannot install them.
CORE_COMMANDS = ("kubectl",)

# Section keys read by the runner itself, never passed to modules.
ENVELOPE_KEYS = frozenset({"module"})

# Environment id: always generated by the runner. Environment modules use it to
# name what they create (cluster, containers, files, cloud resources), so it is
# kept to lowercase letters, digits and '-' (at most 40 characters): a legal
# file name, easy to type in a terminal.
ENVIRONMENT_ID_PATTERN = re.compile(r"^[a-z0-9](?:[a-z0-9-]{0,38}[a-z0-9])?$")
_ENVIRONMENT_ID_MAX_LENGTH = 40


class RunnerInterrupted(RuntimeError):
    pass


def _utc_timestamp() -> str:
    return datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")


def _safe_name(value: str) -> str:
    allowed = []
    for char in value.lower():
        if char.isalnum() or char in {"-", "_"}:
            allowed.append(char)
        elif char.isspace():
            allowed.append("-")
    return "".join(allowed).strip("-") or "scenario"


def build_run_id(config: ScenarioConfig) -> str:
    return f"{_safe_name(config.name)}-{_utc_timestamp()}-seed{config.seed}"


def build_environment_id(config: ScenarioConfig, run_id: str) -> str:
    """`<scenario>-<seed>-<hash of run id>`, see ENVIRONMENT_ID_PATTERN."""
    suffix = f"-{config.seed}-{hashlib.sha1(run_id.encode()).hexdigest()[:6]}"
    ascii_name = (
        unicodedata.normalize("NFKD", config.name).encode("ascii", "ignore").decode().lower()
    )
    base = "".join(c if c.isalnum() else "-" for c in ascii_name)
    base = re.sub(r"-+", "-", base)
    base = base[: _ENVIRONMENT_ID_MAX_LENGTH - len(suffix)].strip("-") or "env"
    environment_id = f"{base}{suffix}"
    if not ENVIRONMENT_ID_PATTERN.match(environment_id):
        raise RuntimeError(f"Generated environment id is invalid: {environment_id!r}")
    return environment_id


@dataclass(frozen=True)
class Component:
    """A scenario section bound to its module and resolved arguments."""

    role: str
    module: ModuleSpec
    options: tuple[str, ...]


def load_component(index: ModuleIndex, raw: dict[str, Any], role: str) -> Component:
    return load_section(index, raw[role], role)


def load_section(index: ModuleIndex, section: dict[str, Any], role: str) -> Component:
    module = load_module(index, str(section["module"]), expected_type=role)
    values = resolve_args(section, module.arg_schema, role, envelope_keys=ENVELOPE_KEYS)
    return Component(role=role, module=module, options=tuple(to_cli_args(values)))


def _collect_kubernetes_state(
    kubeconfig: str,
    paths: RunPaths,
    repo_root: Path,
) -> None:
    commands = {
        "nodes.yaml": [
            "kubectl",
            "--kubeconfig",
            kubeconfig,
            "get",
            "nodes",
            "-o",
            "yaml",
        ],
        "pods.yaml": [
            "kubectl",
            "--kubeconfig",
            kubeconfig,
            "get",
            "pods",
            "-A",
            "-o",
            "yaml",
        ],
        "services.yaml": [
            "kubectl",
            "--kubeconfig",
            kubeconfig,
            "get",
            "svc",
            "-A",
            "-o",
            "yaml",
        ],
        "deployments.yaml": [
            "kubectl",
            "--kubeconfig",
            kubeconfig,
            "get",
            "deployments",
            "-A",
            "-o",
            "yaml",
        ],
        "events.txt": [
            "kubectl",
            "--kubeconfig",
            kubeconfig,
            "get",
            "events",
            "-A",
            "--sort-by=.lastTimestamp",
        ],
    }

    for filename, command in commands.items():
        output_path = paths.kubernetes / filename
        with output_path.open("w", encoding="utf-8") as stream:
            subprocess.run(
                command,
                cwd=str(repo_root),
                text=True,
                stdout=stream,
                stderr=subprocess.STDOUT,
                check=False,
            )


def _print_step(
    component: str,
    action: str,
    status: str,
    *,
    verbose: bool = False,
) -> None:
    if verbose:
        print(
            f"[{component}]{' ' * (16 - len(component))}{action:<10} {status}",
            flush=True,
        )
    else:
        print(
            f"\r\033[K[{component}]{' ' * (16 - len(component))}{action:<10} {status}",
            end="",
            flush=True,
        )


def _run_step(
    component: str,
    action: str,
    command: Sequence[str],
    *,
    cwd: Path,
    env: dict[str, str] | None = None,
    log_file: Path | None = None,
    verbose: bool = False,
    quiet: bool = False,
    check: bool = True,
) -> subprocess.CompletedProcess[str]:

    if not quiet:
        _print_step(component, action, "...", verbose=verbose)

    try:
        result = run_command(
            command,
            cwd=cwd,
            env=env,
            log_file=log_file,
            check=check,
            verbose=verbose,
        )

        if not quiet:
            _print_step(component, action, "✓", verbose=verbose)
            print()

        return result

    except BaseException:
        if not quiet:
            _print_step(component, action, "ERROR", verbose=verbose)
            print()

        raise


def _write_run_window(data_dir: Path, start: float, end: float) -> None:
    """Standard data `run-window`: when the run's wait started and ended, i.e. the
    window in which every module was running (Unix seconds, with decimals). Written even if
    the wait is interrupted (then `end` is the interruption)."""
    window_dir = data_dir / "run-window"
    window_dir.mkdir(parents=True, exist_ok=True)
    (window_dir / "run-window.csv").write_text(
        f"start,end\n{start:.3f},{end:.3f}\n", encoding="utf-8"
    )


class _Steps:
    """Calls module actions and records one manifest event per call."""

    def __init__(
        self,
        paths: RunPaths,
        manifest: RunManifest,
        *,
        utils_path: Path,
        verbose: bool,
        quiet: bool,
    ) -> None:
        self.paths = paths
        self.manifest = manifest
        self.utils_path = utils_path
        self.verbose = verbose
        self.quiet = quiet

    def call(
        self,
        component: Component,
        action: str,
        *positionals: Any,
        check: bool = True,
    ) -> subprocess.CompletedProcess[str] | None:
        module = component.module
        if not module.supports(action):
            return None

        log_dir = self.paths.module_logs(module.name)
        runner_values: dict[str, Any] = {}
        if "log_dir" in module.arg_schema:
            runner_values["log_dir"] = log_dir
        if "extras_dir" in module.arg_schema:
            runner_values["extras_dir"] = self.paths.module_extras(module.name)
        command = module.command(
            action,
            positionals,
            options=(*to_cli_args(runner_values), *component.options),
        )
        with self._event(f"{component.role}.{action}", module=module.name) as event:
            result = _run_step(
                component=component.role,
                action=action,
                command=command,
                cwd=module.module_path,
                env={UTILS_PATH_ENV: str(self.utils_path)},
                log_file=log_dir / f"{action}.log",
                check=check,
                verbose=self.verbose,
                quiet=self.quiet,
            )
            event["returncode"] = result.returncode
            if result.returncode != 0:
                event["status"] = "failed"
        return result

    def wait(self, duration_seconds: int) -> None:
        with self._event("run.wait", duration_seconds=duration_seconds):
            if not self.quiet:
                _print_step("run", "wait", "...", verbose=self.verbose)
            start = time.time()
            try:
                _sleep_with_interrupt(duration_seconds)
            finally:
                _write_run_window(self.paths.data, start, time.time())
            if not self.quiet:
                _print_step("run", "wait", "✓", verbose=self.verbose)
                print()

    def _event(self, event_type: str, **fields: Any) -> _Event:
        return _Event(self.manifest, event_type, fields)


class _Event:
    """Manifest event with a call and a return timestamp."""

    def __init__(self, manifest: RunManifest, event_type: str, fields: dict[str, Any]) -> None:
        self.manifest = manifest
        self.record: dict[str, Any] = {"type": event_type, **fields}

    def __enter__(self) -> dict[str, Any]:
        self.record["called_at"] = utc_now_iso()
        return self.record

    def __exit__(self, exc_type, exc, tb) -> None:
        self.record["returned_at"] = utc_now_iso()
        if exc_type is None:
            self.record.setdefault("status", "completed")
        elif issubclass(exc_type, KeyboardInterrupt):
            self.record["status"] = "interrupted"
        else:
            self.record["status"] = "failed"
            self.record["error"] = str(exc)
        self.manifest.append_event(self.record)


def _sleep_with_interrupt(duration_seconds: int) -> None:
    end = time.monotonic() + duration_seconds

    while time.monotonic() < end:
        time.sleep(min(1.0, end - time.monotonic()))


def utils_path(repo_root: Path) -> Path:
    """The platform's `utils/` directory, given to modules as BENCHMARK_UTILS_PATH."""
    return (repo_root / "utils").resolve()


@dataclass(frozen=True)
class PreparedScenario:
    components: dict[str, Component]
    post_processing: tuple[Component, ...]  # in execution order

    @property
    def all(self) -> list[Component]:
        return [*self.components.values(), *self.post_processing]


def prepare_scenario(config: ScenarioConfig, *, repo_root: Path) -> PreparedScenario:
    """Load and validate every module of the scenario and check their
    dependencies. Creates nothing: used by both `validate` and `run`."""
    missing = [c for c in CORE_COMMANDS if shutil.which(c) is None]
    if missing:
        raise DependencyError(
            f"Missing prerequisite(s) of the platform: {', '.join(missing)} "
            f"(install them manually)."
        )
    raw = config.raw
    index = discover(repo_root)
    components = {role: load_component(index, raw, role) for role in REQUIRED_COMPONENTS}
    post_processing = tuple(
        load_section(index, section, "post-processing")
        for section in post_processing_sections(raw)
    )
    prepared = PreparedScenario(components=components, post_processing=post_processing)
    check_dependencies(index, [c.module.name for c in prepared.all], utils_path(repo_root))
    return prepared


def run_scenario(
    config: ScenarioConfig,
    *,
    repo_root: Path,
    verbose: bool = False,
    quiet: bool = False,
    registry: EnvironmentRegistry | None = None,
) -> Path:
    # Load and validate every module, and check dependencies, before creating anything.
    prepared = prepare_scenario(config, repo_root=repo_root)
    components = prepared.components
    post_processing = prepared.post_processing

    run_id = build_run_id(config)
    environment_id = build_environment_id(config, run_id)
    # Absolute paths: modules run from their own directory, so a path relative
    # to the caller's working directory would point elsewhere for them.
    paths = RunPaths.create((config.output_root / run_id).resolve())
    shutil.copy2(config.path, paths.config)

    manifest = RunManifest(
        paths.manifest,
        {
            "run_id": run_id,
            "scenario": config.name,
            "seed": config.seed,
            "environment_id": environment_id,
            "status": "running",
            "started_at": utc_now_iso(),
            "config": str(paths.config),
            "modules": {c.role: c.module.as_manifest_record() for c in prepared.all},
            "paths": {
                "data": str(paths.data),
                "extras": str(paths.extras),
                "logs": str(paths.logs),
                "runtime": str(paths.runtime),
                "kubernetes": str(paths.kubernetes),
            },
        },
    )

    if not quiet:
        print(f"Run: {paths.root}")
        print(f"Environment id: {environment_id}")

    steps = _Steps(paths, manifest, utils_path=utils_path(repo_root), verbose=verbose, quiet=quiet)
    environment = components["environment"]
    kubeconfig: str | None = None
    launched: list[Component] = []
    interrupted = False

    # Registered *before* create, so that an interrupted create is still known;
    # unregistered only once destroy succeeds.
    registry = registry or EnvironmentRegistry()
    registry.register(
        environment_id, environment.module, environment.options, paths.root, utils_path(repo_root)
    )

    try:
        steps.call(environment, "create", config.seed, environment_id, paths.environment_result)

        if not paths.environment_result.is_file():
            raise RuntimeError("Environment create did not produce a result file.")
        kubeconfig = paths.environment_result.read_text(encoding="utf-8").strip()
        paths.environment_result.unlink()
        if not kubeconfig:
            raise RuntimeError("Environment create produced an empty result file.")

        shutil.copy2(kubeconfig, paths.kubeconfig)
        manifest.set(
            "environment",
            {
                "module": environment.module.name,
                "id": environment_id,
                "kubeconfig": str(paths.kubeconfig),
                "original_kubeconfig": kubeconfig,
            },
        )

        # A component is recorded as launched *before* its launch action, so that
        # its stop action also runs if the launch fails half-way (stop actions
        # must handle dirty states).
        launched.append(components["observability"])
        steps.call(components["observability"], "start", kubeconfig, paths.data)

        launched.append(components["stack"])
        steps.call(components["stack"], "deploy", kubeconfig, config.seed)

        launched.append(components["optimizer"])
        steps.call(components["optimizer"], "start", kubeconfig)

        # Traffic starts right before the wait, once the optimizer is installed:
        # the load shape then starts with the run window, the same for every
        # optimizer, however long it takes to start.
        launched.append(components["traffic"])
        steps.call(components["traffic"], "start", kubeconfig, config.seed, paths.data)

        steps.wait(config.duration_seconds)

        manifest.update(status="completed")
        return paths.root

    except KeyboardInterrupt as exc:
        interrupted = True
        manifest.update(status="interrupted", error="Interrupted by user")
        raise RunnerInterrupted("Benchmark run interrupted by user.") from exc

    except BaseException as exc:
        manifest.update(status="failed", error=str(exc))
        raise

    finally:
        try:
            try:
                if kubeconfig:
                    for component in reversed(launched):
                        steps.call(component, STOP_ACTIONS[component.role], kubeconfig, check=False)

                    # Kubernetes state collection is internal runner bookkeeping,
                    # so it is deliberately not displayed in the progress dashboard.
                    manifest.append_event(
                        {"time": utc_now_iso(), "type": "kubernetes.collect-state"}
                    )
                    _collect_kubernetes_state(kubeconfig, paths, repo_root)

                    manifest.append_event({"time": utc_now_iso(), "type": "provenance.collect"})
                    try:
                        provenance = build_provenance(
                            pods_yaml_path=paths.kubernetes / "pods.yaml",
                            kubeconfig=kubeconfig,
                            artifacts_dir=paths.extras,
                            cleanup_environment=config.cleanup_environment,
                        )
                        manifest.set("provenance", provenance)
                    except Exception as exc:  # provenance capture must never fail the run
                        manifest.set("provenance", {"error": str(exc)})
            finally:
                # Always destroy the environment, even if `create` failed or was
                # interrupted: `destroy <id>` must handle dirty states.
                if config.cleanup_environment:
                    result = steps.call(environment, "destroy", environment_id, check=False)
                    if result is not None and result.returncode == 0:
                        registry.unregister(environment_id)

            # Post-processing only reads standard data, so it runs after the
            # environment is gone, module after module in the scenario's order
            # (each one may read what the previous ones wrote in data/).
            # Skipped when the user interrupted the run.
            if not interrupted:
                for module in post_processing:
                    steps.call(module, "run", paths.data, check=False)
        finally:
            manifest.update(ended_at=utc_now_iso())
